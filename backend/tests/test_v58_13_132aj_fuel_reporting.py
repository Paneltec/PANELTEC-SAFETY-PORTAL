"""v58.13.132aj — Fuel Report enhancements.

Locks in five behavior changes:

  1. `totals.latest_txn_date_iso` returned on every report response,
     powers the FE empty-state banner.
  2. New `top_by_fill_litres` payload sorted by per-fill litres desc.
  3. New `top_dpl_outliers_real` — $/L outliers filtered to
     non-provisional-priced fills only. Empty when all rows are on
     the .132t `$3.00` placeholder.
  4. CSV export gains a metadata header block (Report range, Scope,
     Period, Generated, Generated by, Latest txn on file).
  5. `?detail=1` CSV mode returns per-fill rows with a `Date` column.
"""
from __future__ import annotations

import pytest
import requests

pytestmark = pytest.mark.live_db_writes

BASE = "http://localhost:8001"
ADMIN_EMAIL = "stephen@paneltec.com.au"
ADMIN_PASS = "Mcgstephen50#"


@pytest.fixture(scope="module")
def admin_token() -> str:
    r = requests.post(
        f"{BASE}/api/auth/login",
        json={"email": ADMIN_EMAIL, "password": ADMIN_PASS},
        timeout=10,
    )
    assert r.status_code == 200, r.text
    body = r.json()
    tok = body.get("access_token") or body.get("token")
    assert tok, f"no token in {body}"
    return tok


def _hdr(tok: str) -> dict:
    return {"Authorization": f"Bearer {tok}"}


@pytest.mark.live_db_writes
def test_report_returns_latest_txn_date_iso(admin_token):
    """Fix 1 — totals.latest_txn_date_iso is populated on every response."""
    # Last-week window (known populated) — banner should NOT fire but
    # the field must still be present.
    r = requests.get(
        f"{BASE}/api/fleet/fuel/reports",
        params={"scope": "admin", "period": "weekly",
                "from": "2026-08-31", "to": "2026-09-06"},
        headers=_hdr(admin_token), timeout=15,
    )
    assert r.status_code == 200, r.text
    totals = r.json()["totals"]
    assert "latest_txn_date_iso" in totals
    assert "latest_txn_timestamp" in totals
    # There IS data on file — the field must be a real ISO date, not empty.
    assert totals["latest_txn_date_iso"], "latest_txn_date_iso empty even though data exists"
    assert len(totals["latest_txn_date_iso"]) == 10  # YYYY-MM-DD


@pytest.mark.live_db_writes
def test_empty_range_still_returns_latest_txn_date_iso(admin_token):
    """Fix 1 — empty-state banner needs latest_txn_date_iso EVEN WHEN
    the current filter returned no fills. This is the specific case
    the .132aj banner solves (`This week` returns 0 rows)."""
    r = requests.get(
        f"{BASE}/api/fleet/fuel/reports",
        params={"scope": "admin", "period": "weekly",
                "from": "2036-01-01", "to": "2036-01-07"},  # far future → empty
        headers=_hdr(admin_token), timeout=15,
    )
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["totals"]["fills"] == 0
    # Even with fills==0, the field is populated so the banner can render.
    assert body["totals"]["latest_txn_date_iso"], (
        "latest_txn_date_iso must survive an empty range so the empty-state "
        "banner can tell the user when the pipeline last saw data"
    )


@pytest.mark.live_db_writes
def test_top_by_fill_litres_sorted_desc(admin_token):
    """Fix 5a — Top 5 highest fills, per-transaction, litres desc."""
    r = requests.get(
        f"{BASE}/api/fleet/fuel/reports",
        params={"scope": "admin", "period": "weekly",
                "from": "2026-08-31", "to": "2026-09-06"},
        headers=_hdr(admin_token), timeout=15,
    )
    assert r.status_code == 200
    body = r.json()
    top = body.get("top_by_fill_litres")
    assert top is not None, "top_by_fill_litres key missing from payload"
    assert 1 <= len(top) <= 5
    # Verify descending sort on litres.
    litres = [row["litres"] for row in top]
    assert litres == sorted(litres, reverse=True), (
        f"top_by_fill_litres must be sorted litres desc — got {litres}"
    )
    # Per-fill shape: date, timestamp, vehicle rego / description, driver.
    for row in top:
        for k in ("litres", "total_price", "date_iso", "timestamp",
                  "registration", "driver", "price_source"):
            assert k in row, f"top_by_fill_litres row missing {k!r}"


