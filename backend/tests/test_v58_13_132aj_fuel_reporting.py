@pytest.mark.live_db_writes
def test_export_csv_has_metadata_header(admin_token):
    """Fix 3a — Aggregated CSV export prepends metadata block."""
    r = requests.get(
        f"{BASE}/api/fleet/fuel/reports/export",
        params={"scope": "admin", "period": "weekly",
                "from": "2026-08-31", "to": "2026-09-06"},
        headers=_hdr(admin_token), timeout=15,
    )
    assert r.status_code == 200
    text = r.content.decode("utf-8")
    lines = text.splitlines()
    # First rows are the metadata block.
    assert lines[0].startswith("Report range,"), f"first line was {lines[0]!r}"
    assert "2026-08-31" in lines[0]
    assert "2026-09-06" in lines[0]
    assert lines[1].startswith("Scope,admin")
    assert lines[2].startswith("Period,weekly")
    assert lines[3].startswith("Generated,")
    assert lines[4].startswith("Generated by,")
    assert lines[5].startswith("Latest txn on file,")
    # Blank separator row.
    assert lines[6] == ""
    # Data header on row 7. v58.13.132ak swap: `Fills` col replaced
    # by `Last fill` (date), inserted right after the label.
    assert lines[7].startswith("Admin,Last fill,Litres,Total price"), (
        f"data header not on line 7 — got {lines[7]!r}"
    )


@pytest.mark.live_db_writes
def test_export_csv_detail_mode_has_per_fill_rows_with_date(admin_token):
    """Fix 3b — `?detail=1` returns per-fill CSV with Date column."""
    r = requests.get(
        f"{BASE}/api/fleet/fuel/reports/export",
        params={"scope": "admin", "period": "weekly",
                "from": "2026-08-31", "to": "2026-09-06",
                "detail": 1},
        headers=_hdr(admin_token), timeout=15,
    )
    assert r.status_code == 200
    text = r.content.decode("utf-8")
    lines = text.splitlines()
    # Metadata block includes an extra "Detail mode" row.
    assert any(l.startswith("Detail mode,per-fill") for l in lines[:8]), (
        f"metadata block missing detail marker — first 8 lines: {lines[:8]!r}"
    )
    # Locate the data-header row.
    header_line = next(l for l in lines if l.startswith("Date,Time,"))
    assert "Vehicle rego" in header_line
    assert "Driver" in header_line
    assert "Litres" in header_line
    assert "Total price" in header_line
    assert "$/L" in header_line
    # At least one data row after the header, and the first field
    # must be a YYYY-MM-DD date.
    idx = lines.index(header_line)
    data_rows = [l for l in lines[idx + 1:] if l]
    assert len(data_rows) >= 1
    first = data_rows[0].split(",")
    assert len(first[0]) == 10 and first[0][4] == "-" and first[0][7] == "-", (
        f"first cell of first data row must be YYYY-MM-DD, got {first[0]!r}"
    )
    # Content-Disposition names it as detail file.
    assert "detail" in r.headers.get("content-disposition", "").lower()


